#!/usr/bin/env python3
"""Descriptive companion to the Preregistration 3 panel: where does the single- versus
multi-instance gap come from?

For every pool, take each question's top-1 class under single-instance (original database)
equivalence (highest count, ties broken by the larger representative string) and count how
often that class passes the original database but fails the suite. The analyser breaks top-class
ties by its internal class key, which the per-question file does not contain, so this is an
approximation of its top-1: the output records, per pool, whether the two agree (10 of the 12
Preregistration 3 pools agree exactly; XiYanSQL seed 101 and OmniSQL seed 303 differ by one
question). This is a post hoc, descriptive computation on four non-independent
model points; it is not a preregistered analysis and it decides nothing. Reads the per-question
files the analyser writes; writes experiments/c4_gap_source_descriptive.json.
"""
import collections, json

POOLS = {
    "kwai-autosql-32b": [f"experiments/c4_kwai-autosql-32b_seed{s}_results" for s in (101, 202, 303)],
    "kwai-autosql-14b": [f"experiments/c4_kwai-autosql-14b_seed{s}_results" for s in (101, 202, 303)],
    "xiyansql-32b (fresh)": [f"experiments/c4_xiyansql-32b_seed{s}_results" for s in (101, 202, 303)],
    "omnisql-32b": [f"experiments/c4_omnisql-32b_seed{s}_results" for s in (101, 202, 303)],
    "xiyansql-32b (prior)": ["experiments/c2_results", "experiments/c2_genseed11_results",
                             "experiments/c2_genseed22_results", "experiments/c2_genseed33_results"],
}


def stats(stem):
    qs = json.load(open(stem + "_official_per_question.json"))["questions"]
    n = len(qs); weak = strong = spurious = 0; per_db = collections.Counter(); mass = []
    for q in qs:
        if not q["single"]:
            continue
        top = max(q["single"], key=lambda c: (c["count"], c["representative"]))
        weak += top["weak_ok"]; strong += top["strong_ok"]
        mass.append(top["count"] / max(1, q["n_usable"]))
        if top["weak_ok"] and not top["strong_ok"]:
            spurious += 1; per_db[q["db"]] += 1
    analyser_top1 = json.load(open(stem + "_official.json"))["top1_accuracy_under_strong_oracle"]
    return {"top1_weak": round(weak / n, 4), "top1_strong": round(strong / n, 4), "analyser_top1_strong": analyser_top1,
            "weak_ok_strong_wrong": round(spurious / n, 4), "top_class_mass_mean": round(sum(mass) / len(mass), 3), "per_db": per_db}


def main():
    out = {}
    for tag, stems in POOLS.items():
        rows = [stats(s) for s in stems]
        agg = collections.Counter()
        for r in rows:
            agg.update(r["per_db"])
        out[tag] = {k: [r[k] for r in rows] for k in ("top1_weak", "top1_strong", "analyser_top1_strong", "weak_ok_strong_wrong", "top_class_mass_mean")}
        out[tag]["spurious_per_db_summed_over_pools"] = dict(agg.most_common(6))
        out[tag]["top1_matches_analyser"] = all(abs(r["top1_strong"] - r["analyser_top1_strong"]) < 1e-9 for r in rows)
        print(tag, json.dumps(out[tag]))
    out["_note"] = ("post hoc descriptive table, generated by experiments/c4_gap_source.py from the analyser's "
                    "per-question files. Its top-1 tie rule takes the larger representative string, which "
                    "APPROXIMATES the analyser's larger-class-key rule because the per-question file does not carry "
                    "the class key; top1_matches_analyser records, per pool, whether the two agree.")
    json.dump(out, open("experiments/c4_gap_source_descriptive.json", "w"), indent=1, ensure_ascii=False)


if __name__ == "__main__":
    main()
